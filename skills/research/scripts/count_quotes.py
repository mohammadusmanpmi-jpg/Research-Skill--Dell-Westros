#!/usr/bin/env python3
"""Count themes, tags, brands and segments in a 01-quotes.jsonl file.

Usage: python count_quotes.py research/<brand>/01-quotes.jsonl > research/<brand>/01-counts.md

Deduplicates near-identical quotes (same normalised text), then prints markdown
tables with computed counts and frequency bands. Consolidation reads this file
instead of estimating counts.
"""
import json
import re
import sys
from collections import Counter, defaultdict

BANDS = [  # (name, min_mentions, min_sources)
    ("DOMINANT", 30, 4),
    ("HIGH", 15, 3),
    ("MODERATE", 6, 2),
    ("LOW", 3, 1),
    ("RARE", 1, 1),
]


def band(mentions, sources):
    for name, m, s in BANDS:
        if mentions >= m and sources >= s:
            return name
    return "RARE"


def norm(text):
    # Unicode-aware so non-English quotes (the target market's language) are not collapsed together.
    return re.sub(r"[^\w ]", "", text.lower(), flags=re.UNICODE).strip()[:160]


def load(path):
    records, bad = [], 0
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                bad += 1
                continue
            if not r.get("url") or not r.get("quote"):
                bad += 1
                continue
            records.append(r)
    return records, bad


def main(path):
    records, bad = load(path)
    seen, deduped = set(), []
    for r in records:
        key = norm(r["quote"])
        if key in seen:
            continue
        seen.add(key)
        deduped.append(r)

    by_source = Counter(r["source"] for r in deduped)
    theme_count = Counter()
    theme_sources = defaultdict(set)
    theme_tags = defaultdict(Counter)
    theme_segments = defaultdict(Counter)
    theme_example = {}
    tag_count = Counter()
    brand_sent = defaultdict(Counter)
    segment_count = Counter()
    costs, durations = [], []

    for r in deduped:
        t = r.get("theme") or "untagged"
        theme_count[t] += 1
        theme_sources[t].add(r["source"])
        theme_segments[t][r.get("segment") or "unknown"] += 1
        for tag in r.get("tags") or []:
            tag_count[tag] += 1
            theme_tags[t][tag] += 1
        if t not in theme_example or (r.get("engagement") or 0) > (theme_example[t].get("engagement") or 0):
            theme_example[t] = r
        if r.get("brand"):
            brand_sent[r["brand"]][r.get("sentiment") or "unstated"] += 1
        segment_count[r.get("segment") or "unknown"] += 1
        if r.get("cost") is not None:
            costs.append((r["cost"], r["url"]))
        if r.get("duration") is not None:
            durations.append((r["duration"], r["url"]))

    out = []
    p = out.append
    p("# Computed counts (generated by count_quotes.py – do not edit by hand)\n")
    p(f"Records read: {len(records)} · rejected (no url/quote or bad JSON): {bad} · after dedup: {len(deduped)}\n")
    p("## Quotes per source\n")
    p("| Source | Quotes |\n|---|---|")
    for s, n in by_source.most_common():
        p(f"| {s} | {n} |")
    p("\n## Themes by frequency\n")
    p("| Theme | Mentions | Sources | Band | Top tags | Segments | Example (highest engagement) | URL |\n|---|---|---|---|---|---|---|---|")
    for t, n in theme_count.most_common():
        srcs = theme_sources[t]
        tags = ", ".join(f"{k} {v}" for k, v in theme_tags[t].most_common(3))
        segs = ", ".join(f"{k} {v}" for k, v in theme_segments[t].most_common())
        ex = theme_example[t]
        q = ex["quote"].replace("|", "/").replace("\n", " ")
        q = q[:140] + ("…" if len(q) > 140 else "")
        p(f"| {t} | {n} | {len(srcs)} | {band(n, len(srcs))} | {tags} | {segs} | {q} | {ex['url']} |")
    p("\n## Tags\n")
    p("| Tag | Count |\n|---|---|")
    for t, n in tag_count.most_common():
        p(f"| {t} | {n} |")
    p("\n## Segments\n")
    p("| Segment | Quotes |\n|---|---|")
    for s, n in segment_count.most_common():
        p(f"| {s} | {n} |")
    p("\n## Brands mentioned (sentiment)\n")
    p("| Brand | Positive | Negative | Mixed | Unstated |\n|---|---|---|---|---|")
    for b, c in sorted(brand_sent.items(), key=lambda kv: -sum(kv[1].values())):
        p(f"| {b} | {c['positive']} | {c['negative']} | {c['mixed']} | {c['unstated']} |")
    p("\n## Cost mentions\n")
    for c, u in costs[:100]:
        p(f"- {c} – {u}")
    if not costs:
        p("- none recorded")
    p("\n## Duration mentions\n")
    for d, u in durations[:100]:
        p(f"- {d} – {u}")
    if not durations:
        p("- none recorded")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
