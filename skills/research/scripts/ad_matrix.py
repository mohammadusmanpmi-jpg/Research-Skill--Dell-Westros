#!/usr/bin/env python3
"""Build the competitor angle / avatar matrix from 01-ads.jsonl.

Usage: python ad_matrix.py research/<brand>/01-ads.jsonl [--brand <our-advertiser-name>] > research/<brand>/01-ad-matrix.md

Each line of 01-ads.jsonl is one ad (see phase1-collectors.md §Ads). This script
computes, per angle and per avatar: advertisers, ads, active ads, longest run,
variations, and a status (OPEN / EMERGING / PROVEN / CROWDED / ABANDONED).
Phase 3 reads this file instead of estimating saturation.
"""
import json
import sys
from collections import defaultdict
from datetime import date


def parse_date(s):
    try:
        return date.fromisoformat(str(s)[:10])
    except (TypeError, ValueError):
        return None


def run_days(ad, today):
    if ad.get("days_running") is not None:
        return ad["days_running"]
    start = parse_date(ad.get("first_seen"))
    if not start:
        return ad.get("run_days") or 0
    end = today if ad.get("active") else (parse_date(ad.get("last_seen")) or today)
    return max((end - start).days, 0)


def status(advertisers, active_ads, longest, total_ads):
    # Long-running ads mean someone is profitable on this angle.
    proven_advertisers = advertisers["proven"]
    if total_ads == 0:
        return "OPEN"
    if active_ads == 0 and longest < 21:
        return "ABANDONED"
    if proven_advertisers >= 3:
        return "CROWDED"
    if proven_advertisers >= 1:
        return "PROVEN"
    return "EMERGING"


def summarise(groups, today):
    rows = []
    for key, ads in groups.items():
        by_adv = defaultdict(list)
        for a in ads:
            by_adv[a.get("advertiser", "?")].append(a)
        days = [run_days(a, today) for a in ads]
        active = sum(1 for a in ads if a.get("active"))
        proven = sum(1 for adv_ads in by_adv.values() if max(run_days(a, today) for a in adv_ads) >= 30)
        longest = max(days) if days else 0
        best = max(ads, key=lambda a: run_days(a, today))
        rows.append({
            "key": key,
            "advertisers": len(by_adv),
            "adv_names": ", ".join(sorted(by_adv)),
            "ads": len(ads),
            "active": active,
            "longest": longest,
            "variations": sum(a.get("variations") or 1 for a in ads),
            "spend": sum(a.get("est_spend") or 0 for a in ads),
            "status": status({"proven": proven}, active, longest, len(ads)),
            "best_hook": (best.get("hook") or "").replace("|", "/").replace("\n", " ")[:120],
            "best_adv": best.get("advertiser", "?"),
            "best_url": best.get("url", ""),
            "mechanisms": ", ".join(sorted({a.get("mechanism") for a in ads if a.get("mechanism")}))[:120],
        })
    order = {"CROWDED": 0, "PROVEN": 1, "EMERGING": 2, "ABANDONED": 3, "OPEN": 4}
    return sorted(rows, key=lambda r: (order[r["status"]], -r["longest"]))


def main(argv):
    if not argv:
        sys.exit(__doc__)
    path = argv[0]
    ours = None
    if "--brand" in argv:
        ours = argv[argv.index("--brand") + 1].lower()
    today = date.today()
    ads, bad = [], 0
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                ads.append(json.loads(line))
            except json.JSONDecodeError:
                bad += 1
    competitor_ads = [a for a in ads if not ours or (a.get("advertiser") or "").lower() != ours]
    our_ads = [a for a in ads if ours and (a.get("advertiser") or "").lower() == ours]

    by_angle, by_avatar, grid = defaultdict(list), defaultdict(list), defaultdict(lambda: defaultdict(int))
    for a in competitor_ads:
        angle = a.get("angle") or "untagged"
        avatar = a.get("avatar") or "untagged"
        by_angle[angle].append(a)
        by_avatar[avatar].append(a)
        grid[angle][avatar] += 1

    out = []
    p = out.append
    p("# Competitor ad matrix (generated by ad_matrix.py – do not edit by hand)\n")
    sources = sorted({a.get("source", "?") for a in ads})
    p(f"Ads read: {len(ads)} · competitor ads: {len(competitor_ads)} · our ads: {len(our_ads)} · bad lines: {bad} · data sources: {', '.join(sources)} · computed {today}\n")
    p("Status: CROWDED = 3+ advertisers with an ad running 30+ days · PROVEN = 1-2 such advertisers · EMERGING = ads exist, none 30+ days yet · ABANDONED = all stopped within 21 days · OPEN = no ads found for the searches logged in 01-ad-searches.md\n")

    for title, groups in (("Angles", by_angle), ("Avatars", by_avatar)):
        p(f"## {title}\n")
        p("| Key | Status | Advertisers | Ads | Active | Longest run (d) | Variations | Est. spend | Mechanisms used | Longest-running hook | Advertiser | URL |")
        p("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for r in summarise(groups, today):
            spend = f"{r['spend']:,}" if r["spend"] else ""
            p(f"| {r['key']} | {r['status']} | {r['advertisers']} ({r['adv_names']}) | {r['ads']} | {r['active']} | {r['longest']} | {r['variations']} | {spend} | {r['mechanisms']} | {r['best_hook']} | {r['best_adv']} | {r['best_url']} |")
        p("")

    avatars = sorted(by_avatar)
    p("## Angle × avatar grid (competitor ad count; blank = nobody)\n")
    p("| Angle | " + " | ".join(avatars) + " |")
    p("|---|" + "---|" * len(avatars))
    for angle in sorted(grid):
        p(f"| {angle} | " + " | ".join(str(grid[angle][av]) if grid[angle][av] else "" for av in avatars) + " |")
    p("")

    if our_ads:
        p("## Our ads\n")
        p("| Angle | Avatar | Hook | Run (d) | Active |\n|---|---|---|---|---|")
        for a in our_ads:
            hook = (a.get("hook") or "").replace("|", "/").replace("\n", " ")[:120]
            p(f"| {a.get('angle')} | {a.get('avatar')} | {hook} | {run_days(a, today)} | {a.get('active')} |")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1:])
